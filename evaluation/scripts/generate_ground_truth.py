"""
Ground-Truth Evaluation Dataset Generator for NovaMart.
Calculates exact numerical answers directly from generated CSV dataset and exports
golden evaluation benchmark dataset to evaluation/datasets/novamart_ground_truth.json.
"""

import json
import os
import sys
from pathlib import Path
import pandas as pd

# Set up paths
root_dir = Path(__file__).resolve().parent.parent.parent
if str(root_dir) not in sys.path:
    sys.path.insert(0, str(root_dir))


def generate_ground_truth_dataset(data_dir: str = "data/output", output_dir: str = "evaluation/datasets"):
    """Compute ground-truth metrics from dataset and save JSON."""
    os.makedirs(output_dir, exist_ok=True)
    print("=== Computing Ground-Truth Evaluation Benchmark Metrics ===")

    # Load CSVs
    tx_df = pd.read_csv(os.path.join(data_dir, "sales_transactions.csv"))
    items_df = pd.read_csv(os.path.join(data_dir, "sales_items.csv"))
    stores_df = pd.read_csv(os.path.join(data_dir, "stores.csv"))
    products_df = pd.read_csv(os.path.join(data_dir, "products.csv"))
    categories_df = pd.read_csv(os.path.join(data_dir, "categories.csv"))
    customers_df = pd.read_csv(os.path.join(data_dir, "customers.csv"))
    inv_df = pd.read_csv(os.path.join(data_dir, "inventory.csv"))

    # Convert date columns
    tx_df["tx_date"] = pd.to_datetime(tx_df["transaction_date"])

    # Question 1: Total Revenue
    total_revenue = round(float(tx_df["total_amount"].sum()), 2)

    # Question 2: Top Store by Revenue
    tx_store = pd.merge(tx_df, stores_df, left_on="store_id", right_on="id")
    store_rev = tx_store.groupby("name")["total_amount"].sum().round(2).reset_index()
    top_store = store_rev.sort_values(by="total_amount", ascending=False).iloc[0]

    # Question 3: Total Units Sold
    total_units_sold = int(items_df["quantity"].sum())

    # Question 4: Top Product Category by Revenue
    items_prod = pd.merge(items_df, products_df, left_on="product_id", right_on="id")
    items_cat = pd.merge(items_prod, categories_df, left_on="category_id", right_on="id")
    cat_rev = items_cat.groupby("name_y")["total_price"].sum().round(2).reset_index()
    top_cat = cat_rev.sort_values(by="total_price", ascending=False).iloc[0]

    # Question 5: Top 5 Best Selling Products by Quantity
    prod_qty = items_prod.groupby("name")["quantity"].sum().reset_index()
    top_5_prods = prod_qty.sort_values(by="quantity", ascending=False).head(5).to_dict(orient="records")

    # Question 6: Highest LTV Customer
    tx_cust = pd.merge(tx_df, customers_df, left_on="customer_id", right_on="id")
    cust_spend = tx_cust.groupby(["customer_code", "first_name", "last_name"])["total_amount"].sum().round(2).reset_index()
    top_cust = cust_spend.sort_values(by="total_amount", ascending=False).iloc[0]

    # Question 7: Products with Total Stock < 50 units across warehouses
    prod_stock = inv_df.groupby("product_id")["quantity_on_hand"].sum().reset_index()
    low_stock_count = int((prod_stock["quantity_on_hand"] < 50).sum())

    # Question 8: Revenue in Calendar Year 2025
    tx_2025 = tx_df[(tx_df["tx_date"] >= "2025-01-01") & (tx_df["tx_date"] < "2026-01-01")]
    rev_2025 = round(float(tx_2025["total_amount"].sum()), 2)

    # Question 9: Total Gross Profit
    items_df["item_cost_total"] = items_df["quantity"] * items_df["cost_price"]
    total_gross_profit = round(float((items_df["total_price"] - items_df["item_cost_total"]).sum()), 2)

    # Question 10: Bandra Flagship Store 2024 vs 2025 Revenue
    bandra_tx = tx_store[tx_store["store_code"] == "STR-MUM-01"]
    rev_bandra_2024 = round(float(bandra_tx[(bandra_tx["tx_date"] >= "2024-01-01") & (bandra_tx["tx_date"] < "2025-01-01")]["total_amount"].sum()), 2)
    rev_bandra_2025 = round(float(bandra_tx[(bandra_tx["tx_date"] >= "2025-01-01") & (bandra_tx["tx_date"] < "2026-01-01")]["total_amount"].sum()), 2)

    ground_truth = [
        {
            "id": "eval_001",
            "category": "Revenue",
            "question": "What was the total sales revenue generated by NovaMart across all historical data?",
            "intent": "Overall Revenue Aggregation",
            "relevant_tables": ["sales_transactions"],
            "expected_sql": "SELECT ROUND(SUM(total_amount), 2) AS total_revenue FROM sales_transactions;",
            "expected_answer": {"total_revenue": total_revenue},
            "expected_viz": "metric_card",
        },
        {
            "id": "eval_002",
            "category": "Store Performance",
            "question": "Which store generated the highest total revenue, and what was the revenue amount?",
            "intent": "Store Performance Ranking",
            "relevant_tables": ["sales_transactions", "stores"],
            "expected_sql": "SELECT s.name, ROUND(SUM(st.total_amount), 2) AS revenue FROM sales_transactions st JOIN stores s ON st.store_id = s.id GROUP BY s.name ORDER BY revenue DESC LIMIT 1;",
            "expected_answer": {"store_name": top_store["name"], "revenue": float(top_store["total_amount"])},
            "expected_viz": "bar_chart",
        },
        {
            "id": "eval_003",
            "category": "Sales Volume",
            "question": "How many total units of products were sold across all sales transactions?",
            "intent": "Sales Volume Aggregation",
            "relevant_tables": ["sales_items"],
            "expected_sql": "SELECT SUM(quantity) AS total_units_sold FROM sales_items;",
            "expected_answer": {"total_units_sold": total_units_sold},
            "expected_viz": "metric_card",
        },
        {
            "id": "eval_004",
            "category": "Category Performance",
            "question": "What is the top product category by total sales revenue, and what was its total revenue?",
            "intent": "Category Performance Ranking",
            "relevant_tables": ["sales_items", "products", "categories"],
            "expected_sql": "SELECT c.name, ROUND(SUM(si.total_price), 2) AS category_revenue FROM sales_items si JOIN products p ON si.product_id = p.id JOIN categories c ON p.category_id = c.id GROUP BY c.name ORDER BY category_revenue DESC LIMIT 1;",
            "expected_answer": {"category_name": top_cat["name_y"], "category_revenue": float(top_cat["total_price"])},
            "expected_viz": "pie_chart",
        },
        {
            "id": "eval_005",
            "category": "Product Performance",
            "question": "What are the top 5 products by total units sold?",
            "intent": "Product Ranking",
            "relevant_tables": ["sales_items", "products"],
            "expected_sql": "SELECT p.name, SUM(si.quantity) AS total_quantity FROM sales_items si JOIN products p ON si.product_id = p.id GROUP BY p.name ORDER BY total_quantity DESC LIMIT 5;",
            "expected_answer": top_5_prods,
            "expected_viz": "horizontal_bar_chart",
        },
        {
            "id": "eval_006",
            "category": "Customer Behavior",
            "question": "Who is the top customer by total lifetime spend, and how much did they spend?",
            "intent": "Customer Lifetime Value Analysis",
            "relevant_tables": ["sales_transactions", "customers"],
            "expected_sql": "SELECT c.customer_code, c.first_name, c.last_name, ROUND(SUM(st.total_amount), 2) AS total_spent FROM sales_transactions st JOIN customers c ON st.customer_id = c.id GROUP BY c.id ORDER BY total_spent DESC LIMIT 1;",
            "expected_answer": {
                "customer_code": top_cust["customer_code"],
                "full_name": f"{top_cust['first_name']} {top_cust['last_name']}",
                "total_spent": float(top_cust["total_amount"]),
            },
            "expected_viz": "kpi_card",
        },
        {
            "id": "eval_007",
            "category": "Inventory",
            "question": "How many products currently have total inventory stock across all warehouses below 50 units?",
            "intent": "Inventory Stock Alert",
            "relevant_tables": ["inventory", "products"],
            "expected_sql": "SELECT COUNT(*) FROM (SELECT product_id, SUM(quantity_on_hand) AS total_stock FROM inventory GROUP BY product_id HAVING SUM(quantity_on_hand) < 50);",
            "expected_answer": {"low_stock_products_count": low_stock_count},
            "expected_viz": "metric_card",
        },
        {
            "id": "eval_008",
            "category": "Time Trends",
            "question": "What was the total revenue in calendar year 2025?",
            "intent": "Time Trend Filtering",
            "relevant_tables": ["sales_transactions"],
            "expected_sql": "SELECT ROUND(SUM(total_amount), 2) AS revenue_2025 FROM sales_transactions WHERE transaction_date >= '2025-01-01' AND transaction_date < '2026-01-01';",
            "expected_answer": {"revenue_2025": rev_2025},
            "expected_viz": "line_chart",
        },
        {
            "id": "eval_009",
            "category": "Profit/Margin",
            "question": "What was the total gross profit generated across all sales line items?",
            "intent": "Profit Margin Analysis",
            "relevant_tables": ["sales_items"],
            "expected_sql": "SELECT ROUND(SUM(total_price - (quantity * cost_price)), 2) AS gross_profit FROM sales_items;",
            "expected_answer": {"total_gross_profit": total_gross_profit},
            "expected_viz": "metric_card",
        },
        {
            "id": "eval_010",
            "category": "Comparative Analysis",
            "question": "What were total sales for NovaMart Bandra Flagship store in 2025 compared to 2024?",
            "intent": "Comparative Store Time Analysis",
            "relevant_tables": ["sales_transactions", "stores"],
            "expected_sql": "SELECT str.name, SUM(CASE WHEN st.transaction_date >= '2024-01-01' AND st.transaction_date < '2025-01-01' THEN st.total_amount ELSE 0 END) AS rev_2024, SUM(CASE WHEN st.transaction_date >= '2025-01-01' AND st.transaction_date < '2026-01-01' THEN st.total_amount ELSE 0 END) AS rev_2025 FROM sales_transactions st JOIN stores str ON st.store_id = str.id WHERE str.store_code = 'STR-MUM-01' GROUP BY str.id;",
            "expected_answer": {
                "store_name": "NovaMart Bandra Flagship",
                "revenue_2024": rev_bandra_2024,
                "revenue_2025": rev_bandra_2025,
                "growth_percentage": round(((rev_bandra_2025 - rev_bandra_2024) / rev_bandra_2024) * 100, 2),
            },
            "expected_viz": "grouped_bar_chart",
        },
    ]

    out_file = os.path.join(output_dir, "novamart_ground_truth.json")
    with open(out_file, "w") as f:
        json.dump(ground_truth, f, indent=2)

    print(f"[SUCCESS] Exported {len(ground_truth)} golden ground-truth evaluation questions to: {out_file}")

    for item in ground_truth:
        print(f"  - [{item['id']}] {item['question'][:65]}... -> {item['expected_answer']}")

    return ground_truth


if __name__ == "__main__":
    generate_ground_truth_dataset()
